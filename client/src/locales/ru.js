// Русский — у русского три формы множественного числа, поэтому строки со
// счётчиком проходят через plural(); там, где согласование получилось бы
// громоздким, использована форма «Выбрано треков: N».
const plural = (n, one, few, many) => {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
};

